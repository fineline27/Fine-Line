#!/usr/bin/env node
/**
 * Sync public.teams current_wins / current_losses from ESPN NBA standings.
 *
 * Usage:
 *   node scripts/refresh-nba-records.mjs           # print SQL (default)
 *   node scripts/refresh-nba-records.mjs --apply   # push to Supabase (needs service role)
 *
 * Loads .env via dotenv. For --apply set SUPABASE_SERVICE_ROLE_KEY (Dashboard → Settings → API).
 */
import 'dotenv/config';
import { createClient } from '@supabase/supabase-js';

const ESPN_STANDINGS =
  'https://site.api.espn.com/apis/v2/sports/basketball/nba/standings';

/** ESPN abbreviations that differ from our teams.abbreviation values. */
const ESPN_TO_APP = {
  GS: 'GSW',
  NY: 'NYK',
  NO: 'NOP',
  SA: 'SAS',
  UTAH: 'UTA',
  WSH: 'WAS',
};

function mapAbbreviation(espnAbbr) {
  return ESPN_TO_APP[espnAbbr] ?? espnAbbr;
}

function statValue(entry, type) {
  const stat = entry.stats?.find((s) => s.type === type);
  return stat?.value ?? 0;
}

async function fetchRecords() {
  const res = await fetch(ESPN_STANDINGS);
  if (!res.ok) {
    throw new Error(`ESPN standings: HTTP ${res.status}`);
  }
  const json = await res.json();
  const records = new Map();

  for (const conference of json.children ?? []) {
    for (const entry of conference.standings?.entries ?? []) {
      const espnAbbr = entry.team?.abbreviation;
      if (!espnAbbr) continue;
      const abbr = mapAbbreviation(espnAbbr);
      records.set(abbr, {
        wins: Math.round(statValue(entry, 'wins')),
        losses: Math.round(statValue(entry, 'losses')),
      });
    }
  }

  if (records.size !== 30) {
    throw new Error(`Expected 30 teams from ESPN, got ${records.size}`);
  }

  return records;
}

function recordsToSql(records) {
  const lines = [
    '-- Generated by scripts/refresh-nba-records.mjs',
    '-- Safe to re-run in Supabase SQL Editor.',
    '',
  ];
  for (const abbr of [...records.keys()].sort()) {
    const { wins, losses } = records.get(abbr);
    lines.push(
      `update public.teams set current_wins = ${wins}, current_losses = ${losses} where abbreviation = '${abbr}';`,
    );
  }
  lines.push('');
  lines.push(
    "select abbreviation, name, current_wins, current_losses from public.teams where sport = 'NBA' order by abbreviation;",
  );
  return lines.join('\n');
}

async function applyToSupabase(records) {
  const url = process.env.SUPABASE_URL ?? process.env.EXPO_PUBLIC_SUPABASE_URL;
  const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
  if (!url || !serviceKey) {
    console.error(
      'Missing SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY. Add them to .env for --apply, or paste the SQL below in the SQL Editor.',
    );
    process.exit(1);
  }

  const supabase = createClient(url, serviceKey);
  for (const [abbr, { wins, losses }] of records) {
    const { error } = await supabase
      .from('teams')
      .update({ current_wins: wins, current_losses: losses })
      .eq('abbreviation', abbr)
      .eq('sport', 'NBA');
    if (error) {
      throw new Error(`${abbr}: ${error.message}`);
    }
  }
  console.log(`Updated ${records.size} teams in Supabase.`);
}

const apply = process.argv.includes('--apply');
const records = await fetchRecords();

if (apply) {
  await applyToSupabase(records);
} else {
  console.log(recordsToSql(records));
}
